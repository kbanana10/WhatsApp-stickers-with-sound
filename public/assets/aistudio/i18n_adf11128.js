  function isRTL() { return lang === "ar"; }
  function setLang(next) {
    if (next !== "ar" && next !== "en") return;
    if (next === lang) return;
    lang = next;
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignore */ }
    listeners.forEach((fn) => { try { fn(lang); } catch (e) { /* ignore */ } });
  }
